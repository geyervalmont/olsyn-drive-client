package fakedrive

import (
	"crypto/md5"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"errors"
	"fmt"
	"hash"
	"io"
	"os"
)

// blob is stored content: pieces held in memory or in files under
// Options.DataDir, or content generated on read (a virtual file of any size
// that takes no space).
type blob struct {
	segs    []segment
	virtual int64 // > 0: generated content of this size
}

type segment struct {
	mem  []byte
	path string
	size int64
}

func memBlob(b []byte) blob { return blob{segs: []segment{{mem: b, size: int64(len(b))}}} }

func (b blob) size() int64 {
	if b.virtual > 0 {
		return b.virtual
	}
	var n int64
	for _, s := range b.segs {
		n += s.size
	}
	return n
}

// writeRange copies n bytes from offset start to w.
func (b blob) writeRange(w io.Writer, start, n int64) error {
	if b.virtual > 0 {
		buf := make([]byte, 64<<10)
		for n > 0 {
			k := min(int64(len(buf)), n)
			fillVirtual(buf[:k], start)
			if _, err := w.Write(buf[:k]); err != nil {
				return err
			}
			start += k
			n -= k
		}
		return nil
	}
	for _, s := range b.segs {
		if n <= 0 {
			break
		}
		if start >= s.size {
			start -= s.size
			continue
		}
		k := min(s.size-start, n)
		if s.mem != nil {
			if _, err := w.Write(s.mem[start : start+k]); err != nil {
				return err
			}
		} else if err := copyFile(w, s.path, start, k); err != nil {
			return err
		}
		start, n = 0, n-k
	}
	if n > 0 {
		return errors.New("fakedrive: range past the end")
	}
	return nil
}

func copyFile(w io.Writer, path string, off, n int64) error {
	f, err := os.Open(path)
	if err != nil {
		return fmt.Errorf("open stored part: %w", err)
	}
	defer f.Close()
	_, err = io.Copy(w, io.NewSectionReader(f, off, n))
	return err
}

// bytes returns the whole content (for small test files; nil when virtual).
func (b blob) bytes() []byte {
	if b.virtual > 0 {
		return nil
	}
	if len(b.segs) == 1 && b.segs[0].mem != nil {
		return append([]byte(nil), b.segs[0].mem...)
	}
	var out writerBuf
	_ = b.writeRange(&out, 0, b.size())
	return out.b
}

// sha256 hashes the content (it reads all of it).
func (b blob) sha256() string {
	h := sha256.New()
	_ = b.writeRange(h, 0, b.size())
	return hex.EncodeToString(h.Sum(nil))
}

type writerBuf struct{ b []byte }

func (w *writerBuf) Write(p []byte) (int, error) { w.b = append(w.b, p...); return len(p), nil }

// fillVirtual writes the generated bytes at offset off: every 8-byte word
// is its own offset scrambled, so any range can be checked without the rest.
func fillVirtual(p []byte, off int64) {
	var word [8]byte
	for i := 0; i < len(p); {
		pos := off + int64(i)
		base := pos &^ 7
		x := uint64(base)*0x9E3779B97F4A7C15 ^ 0x5DEECE66D
		binary.LittleEndian.PutUint64(word[:], x^x>>29)
		k := copy(p[i:], word[pos-base:])
		i += k
	}
}

// VirtualBytes returns the generated content of a virtual file at offset off,
// for tests that check what the client read.
func VirtualBytes(off int64, n int) []byte {
	p := make([]byte, n)
	fillVirtual(p, off)
	return p
}

// storePart reads a part body of exactly size bytes into memory, or into
// a file under dir when dir is set. It returns the part and its MD5 ETag.
func storePart(dir, name string, r io.Reader, size int64) (segment, string, error) {
	h := md5.New()
	if dir == "" {
		data, err := io.ReadAll(io.LimitReader(r, size+1))
		if err != nil {
			return segment{}, "", err
		}
		h.Write(data)
		return segment{mem: data, size: int64(len(data))}, etag(h), nil
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return segment{}, "", fmt.Errorf("make the parts folder: %w", err)
	}
	p := dir + string(os.PathSeparator) + name
	f, err := os.Create(p + ".tmp")
	if err != nil {
		return segment{}, "", fmt.Errorf("store a part: %w", err)
	}
	n, err := io.Copy(io.MultiWriter(f, h), io.LimitReader(r, size+1))
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Rename(p+".tmp", p)
	}
	if err != nil {
		_ = os.Remove(p + ".tmp")
		return segment{}, "", err
	}
	return segment{path: p, size: n}, etag(h), nil
}

func etag(h hash.Hash) string { return "\"" + hex.EncodeToString(h.Sum(nil)) + "\"" }
